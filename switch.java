import java.util.*;
public class switchexample
 {
    public static void main(String[] args){
        Scanner sc = new Scanner(System.in);
        System.out.println("Enter your number in 5 muliple ");
        int num = sc.Nextint();
        switch(num)
        {
            case 5:
                System.out.println("You Entered "+num);
                break;
            case 10:
                System.out.println("You Entered "+num);
                break;
            case 15:
                System.out.println("You Entered "+num);
                break;
            case 20:
                System.out.println("You Entered "+num);
                break;
        }

    }

}
    
   

