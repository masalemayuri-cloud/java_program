class relationalOperator {

    public static void main(String [] main){

        int x = 10;
        int y = 20;
        int z = 30;

        System.out.println("x  > y :" +(x > y));
        System.out.println("x  < y :" +(x < y));
        System.out.println("x  >= y :" +(x >= y));
        System.out.println("x  <= y :" +(x <= y));
        System.out.println("x  == z :" +(x == z));
        System.out.println("x  != z :" +(x != z));
        
    }
}

